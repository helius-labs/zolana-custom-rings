#!/usr/bin/env python3
"""Generate the Rust circuit catalog and verifier dispatch from Go's catalog.

Missing verifier files fail by default. --allow-missing is for development during
key rotation and emits no dispatch entry for a missing key (verification fails closed).
"""
import argparse
import json
import pathlib
import subprocess
from ring_key_layout import verifier_relative_path

ROOT = pathlib.Path(__file__).resolve().parents[1]

def variant(k):
    i, o, w, own = k['Inputs'], k['Outputs'], k['Withdrawals'], str(k['OwnOnly']).lower()
    return [f'DeliveredAudit {{ outputs: {o} }}', f'DeliveredSenderAudit {{ inputs: {i}, outputs: {o} }}',
            f'AnonymousAudit {{ class: {i}, outputs: {o} }}', f'AnonymousEntryAudit {{ class: {i}, outputs: {o} }}',
            f'MemberPolicy {{ outputs: {o}, withdrawals: {w}, own_only: {own} }}',
            f'DelegatePolicy {{ inputs: {i}, outputs: {o}, own_only: {own} }}',
            f'ApplyRecords {{ writes: {i} }}', 'RegisterKey', f'Deposit {{ capacity: {i} }}',
            f'Merge {{ width: {i} }}', 'WithdrawalExemption'][k['Family']]

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--allow-missing', action='store_true')
    args = parser.parse_args()
    catalog = json.loads(subprocess.check_output(['go', 'run', './cmd/catalog'], cwd=ROOT/'prover'))
    directory = ROOT/'program-libs/interface/src'
    verifier_directory = directory/'verifying_keys'
    header = '// Generated by tools/generate_ring_keys.py from the Go circuit catalog.\n'
    rust = header+'use crate::key_catalog::{RingCircuit, RingKey};\n'
    rust += f'pub const RING_KEYS: [RingKey; {len(catalog)}] = [\n'
    verifiers, missing = [], []
    for k in catalog:
        name = k['Circuit']
        rust += f'RingKey {{ circuit: RingCircuit::{variant(k)}, name: "{name}" }},\n'
        module = name.removeprefix('custom-ring-').replace('-', '_')+'_verifying_key'
        path = verifier_relative_path(module)
        if (verifier_directory/path).exists():
            verifiers.append((k,module,name.replace('-','_')+'.key',path))
        else:
            missing.append(name)
    if missing and not args.allow_missing:
        raise SystemExit('Missing verifiers: '+', '.join(missing))
    ring_keys = directory/'proof/ring_keys.rs'
    ring_keys.write_text(rust+'];\n')
    rust = header+'use crate::key_catalog;\n'
    for _, module, _, path in verifiers:
        rust += f'#[path = "{path.as_posix()}"]\npub mod {module};\n'
    rust += 'pub const PROVING_KEY_SHA256S: &[(&str, [u8;32])] = &[\n'
    for _, module, file, _ in verifiers:
        rust += f'("{file}", {module}::VERIFYINGKEY_PROVING_KEY_SHA256),\n'
    rust += '];\npub fn verifying_key(circuit: key_catalog::RingCircuit) -> Option<&\'static groth16_solana::groth16::Groth16Verifyingkey<\'static>> {\nmatch circuit {\n'
    for k,module,_,_ in verifiers:
        rust += f'key_catalog::RingCircuit::{variant(k)} => Some(&{module}::VERIFYINGKEY),\n'
    rust += '_ => None,\n}\n}\n'
    (verifier_directory/'mod.rs').write_text(rust)
    subprocess.run(['rustfmt', '--edition=2021', str(ring_keys), str(verifier_directory/'mod.rs')], check=True)
    lock = json.loads((ROOT/'prover/ring/proving-keys.lock').read_text())
    ts = '// Generated by tools/generate_ring_keys.py from proving-keys.lock.\n'
    ts += 'export const RING_PROVING_KEY_SHA256S: Readonly<Record<string, string>> = Object.freeze({\n'
    for name, entry in sorted(lock['keys'].items()):
        entry_line = f'  "{name}": "{entry["sha256"]}",\n'
        ts += entry_line if len(entry_line.rstrip('\n')) <= 100 else f'  "{name}":\n    "{entry["sha256"]}",\n'
    ts += '});\n'
    (ROOT/'sdk-libs/ts/src/protocol/proof/ring-proving-keys.ts').write_text(ts)
    print(f'Generated {len(catalog)} catalog entries, {len(verifiers)} verifiers, {len(missing)} missing.')

if __name__ == '__main__':
    main()
