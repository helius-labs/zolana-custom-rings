#!/usr/bin/env python3
"""Measure CPU proving times and regenerate BENCHMARK.md and raw JSON samples."""

import argparse
import datetime
import hashlib
import json
import math
import os
import pathlib
import platform
import re
import shlex
import statistics
import subprocess
import tempfile


ROOT = pathlib.Path(__file__).resolve().parents[1]
CASES = ROOT / "prover/ring/proving-benchmarks.json"
REPORT = ROOT / "BENCHMARK.md"
RAW = ROOT / "target/proof-benchmark.json"
RESULT = re.compile(r"^BenchmarkRingProve/(\S+)\s+(\d+)\s+(.+)$")


def positive(value):
    number = int(value)
    if number < 1:
        raise argparse.ArgumentTypeError("must be positive")
    return number


def command(args, cwd=ROOT):
    return subprocess.check_output(args, cwd=cwd, text=True).strip()


def sha256(path):
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def parse_results(output, circuits, samples, iterations):
    results = {circuit: [] for circuit in circuits}
    processors = set()
    for line in output.splitlines():
        match = RESULT.fullmatch(line)
        if match is None:
            continue
        benchmark, count, fields = match.groups()
        if benchmark in results:
            circuit, procs = benchmark, 1
        else:
            circuit, separator, suffix = benchmark.rpartition("-")
            if not separator or not suffix.isdigit() or circuit not in results:
                raise ValueError("unexpected benchmark: " + benchmark)
            procs = int(suffix)
        metrics = {unit: float(value) for value, unit in re.findall(r"([\d.eE+-]+)\s+(\S+)", fields)}
        duration, constraints = metrics["ns/op"], metrics["constraints"]
        if int(count) != iterations or not math.isfinite(duration) or duration <= 0:
            raise ValueError("invalid timing or iteration count: " + circuit)
        if not math.isfinite(constraints) or constraints < 1 or not constraints.is_integer():
            raise ValueError("invalid constraint count: " + circuit)
        if procs < 1:
            raise ValueError("invalid GOMAXPROCS: " + benchmark)
        processors.add(procs)
        results[circuit].append({"ns_per_op": duration, "constraints": int(constraints)})
    for circuit, measured in results.items():
        if len(measured) != samples:
            raise ValueError(f"{circuit}: expected {samples} samples, got {len(measured)}")
        if len({sample["constraints"] for sample in measured}) != 1:
            raise ValueError("constraint count changed: " + circuit)
    if len(processors) != 1:
        raise ValueError("benchmarks must use one GOMAXPROCS setting")
    return results, processors.pop()


def shape(circuit):
    name = circuit.removeprefix("custom-ring-")
    if match := re.fullmatch(r"audit-(packed|delivered)-(\d+)", name):
        layout, outputs = match.groups()
        return f"Confidential audit ({layout})", "—", outputs, "—"
    if match := re.fullmatch(r"audit-anonymous-v2-(\d+)-(\d+)", name):
        inputs, outputs = match.groups()
        return "Anonymous audit", inputs, outputs, "—"
    if match := re.fullmatch(r"policy-member-v2-(\d+)-w(\d+)-(own|curator)", name):
        outputs, withdrawals, registry = match.groups()
        return f"Member policy ({registry})", "—", outputs, withdrawals
    raise ValueError("unknown benchmark shape: " + circuit)


def memory_bytes():
    if platform.system() == "Darwin":
        return int(command(["sysctl", "-n", "hw.memsize"]))
    if hasattr(os, "sysconf") and "SC_PHYS_PAGES" in os.sysconf_names:
        return os.sysconf("SC_PHYS_PAGES") * os.sysconf("SC_PAGE_SIZE")
    return None


def markdown(metadata, results):
    lines = [
        "# Custom ring proving benchmarks", "",
        "Generated by `just bench-proofs`. Regenerate this file from a successful benchmark run.", "",
        f"Measured {metadata['date']}. CPU prover; {metadata['samples']} samples per circuit, "
        f"{metadata['iterations']} timed proofs per sample after an untimed warm-up. "
        "Median and range are calculated from each sample's mean time per proof.", "",
        "| Circuit | Input class | Output capacity | Withdrawal capacity | Constraints | Median (ms) | Range (ms) |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for circuit, samples in results.items():
        label, inputs, outputs, withdrawals = shape(circuit)
        times = [sample["ns_per_op"] / 1e6 for sample in samples]
        lines.append(
            f"| {label} | {inputs} | {outputs} | {withdrawals} | {samples[0]['constraints']:,} | "
            f"{statistics.median(times):.1f} | {min(times):.1f}–{max(times):.1f} |"
        )
    memory = metadata["memory_bytes"]
    memory_text = f"{memory / 2**30:g} GiB RAM" if memory else "RAM unavailable"
    lines.extend([
        "", "## Measurement scope", "",
        "The minimum and maximum output capacities are measured for confidential audit. "
        "Anonymous audit measures the minimum shape, maximum input class at 2 outputs, "
        "and maximum output capacity at input class 1. There is no 32-input/16-output key. "
        "Member policy measures 2 outputs without withdrawals, 16 outputs without withdrawals, "
        "and 16 outputs with the maximum compiled withdrawal capacity, for own and curator registries.", "",
        "Input class and output/withdrawal capacities describe compiled circuits; they do not "
        "guarantee a transaction fits Solana's limits. Anonymous input classes 4, 32 and 1 "
        "use 2, 32 and 1 live inputs respectively. Anonymous fixtures include a pair payment "
        "and change. The 16-output confidential fixture has 15 live outputs; the 16-output "
        "anonymous fixture has 7; 16-output policy fixtures have 10. Remaining output slots "
        "are padding. Policy fixtures exercise list rules, escrow and an outflow cap. "
        "Maximum withdrawal fixtures fill their withdrawal capacity.", "",
        "Timing includes assignment construction, witness encoding, constraint solving and "
        "Groth16 proving through the CPU `ExtensionProof.Prove` path. Key loading, fixture "
        "construction, JSON decoding, warm-up and proof verification are outside the timer. "
        "Warm-up and final proofs are verified. These are independent circuits; SPP proofs, "
        "network requests and transaction submission are excluded. Rows cannot be summed "
        "to claim a measured complete transfer or a comparison against Zolana's combined circuit.", "",
        "## Environment", "",
        f"- Machine: {metadata['cpu']}; {metadata['logical_cpus']} logical CPUs; {memory_text}.",
        f"- System: {metadata['platform']}.",
        f"- Go: {metadata['go_version']}; `GOMAXPROCS={metadata['gomaxprocs']}`.",
        f"- Repository: `{metadata['commit']}`; working tree "
        f"{'modified' if metadata['dirty'] else 'clean'}.",
        f"- Zolana: `{metadata['zolana_commit']}`.",
        f"- Proving keys: pinned release `{metadata['key_release']}`; sizes and SHA-256 digests checked before proving.",
        "", "Raw samples, exact circuit names, benchmark-source hashes and Go output are in "
        "`target/proof-benchmark.json`. Results depend on the machine and background load.", "",
        "## Reproduce", "", "Run from the repository root with the pinned keys installed:", "",
        "```sh", metadata["reproduce"], "```", "",
    ])
    return "\n".join(lines)


def atomic_write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent, delete=False) as output:
        temporary = pathlib.Path(output.name)
        try:
            output.write(text)
            output.close()
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--samples", type=positive, default=5)
    parser.add_argument("--iterations", type=positive, default=3)
    parser.add_argument("--keys-dir", type=pathlib.Path, default=os.environ.get(
        "ZOLANA_PROVER_KEYS_DIR", ROOT / "zolana/prover/server/proving-keys"))
    args = parser.parse_args()
    keys_dir = args.keys_dir.resolve()
    circuits = json.loads(CASES.read_text())
    if not circuits or len(set(circuits)) != len(circuits):
        raise ValueError("benchmark cases must be nonempty and unique")
    lock = json.loads((ROOT / "prover/ring/proving-keys.lock").read_text())
    for circuit in circuits:
        shape(circuit)
        filename = circuit.replace("-", "_") + ".key"
        expected, path = lock["keys"][filename], keys_dir / filename
        if path.stat().st_size != expected["size"] or sha256(path) != expected["sha256"]:
            raise ValueError("proving key differs from the pinned release: " + filename)
    bench_command = ["go", "test", "./ring", "-run", "^$", "-bench", "^BenchmarkRingProve$",
                     f"-benchtime={args.iterations}x", f"-count={args.samples}", "-benchmem", "-timeout=60m"]
    run = subprocess.run(bench_command, cwd=ROOT / "prover", text=True, stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, env={**os.environ, "REQUIRE_RING_KEYS": "1",
                                                       "ZOLANA_PROVER_KEYS_DIR": str(keys_dir)})
    print(run.stdout, end="", flush=True)
    if run.returncode:
        raise SystemExit(run.returncode)
    results, gomaxprocs = parse_results(run.stdout, circuits, args.samples, args.iterations)
    cpu = re.search(r"^cpu: (.+)$", run.stdout, re.MULTILINE)
    metadata = {
        "date": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "samples": args.samples, "iterations": args.iterations,
        "cpu": cpu.group(1) if cpu else platform.processor(),
        "logical_cpus": os.cpu_count(), "memory_bytes": memory_bytes(),
        "platform": (f"macOS {platform.mac_ver()[0]} {platform.machine()}" if platform.system() == "Darwin"
                     else platform.platform()),
        "go_version": command(["go", "version"], ROOT / "prover"),
        "gomaxprocs": gomaxprocs, "commit": command(["git", "rev-parse", "HEAD"]),
        "dirty": bool(command(["git", "status", "--porcelain"])),
        "zolana_commit": command(["git", "rev-parse", "HEAD"], ROOT / "zolana"),
        "key_release": lock["release"], "keys_dir": str(keys_dir),
        "command": bench_command,
        "source_sha256": {str(path.relative_to(ROOT)): sha256(path) for path in (
            CASES, ROOT / "prover/ring/prove_bench_test.go", pathlib.Path(__file__).resolve())},
        "reproduce": f"GOMAXPROCS={gomaxprocs} " + shlex.join([
            "python3", "tools/bench_proofs.py", "--keys-dir", str(keys_dir),
            "--samples", str(args.samples), "--iterations", str(args.iterations)]),
    }
    report = markdown(metadata, results)
    atomic_write(RAW, json.dumps({"metadata": metadata, "timings": results, "go_output": run.stdout}, indent=2) + "\n")
    atomic_write(REPORT, report)
    print("Wrote BENCHMARK.md and target/proof-benchmark.json", flush=True)


if __name__ == "__main__":
    main()
