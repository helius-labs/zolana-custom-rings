fn file_json(description: &str, cases: &[Case]) -> Value {
    json!({
        "description": description,
        "cases": cases.iter().map(|case| case.json.clone()).collect::<Vec<_>>(),
    })
}

fn check_audit(audit: &Audit) {
    let origin = RingOrigin {
        ring_invoked: true,
        event: origin_fixture::event(&audit.transaction),
        signers: Vec::new(),
        pool_accounts: Vec::new(),
        withdrawals: Vec::new(),
        deposits: Vec::new(),
        merge_disclosure: None,
        transact: Some(audit.frame.clone()),
    };
    let layout = origin.disclosure_layout(audit.mode).unwrap();
    assert_eq!(layout, audit.layout);
    let opened = TransactionAudit::new(&audit.transaction, layout)
        .with_input_trees(&audit.input_trees)
        .unwrap()
        .with_known_utxos(&audit.known)
        .with_escrowed_keys(&audit.escrowed)
        .run(&auditor(), &assets())
        .unwrap();
    assert!(
        opened.payload_errors.is_empty(),
        "{:?}",
        opened.payload_errors
    );
    assert_eq!(opened.outputs, audit.outputs);
    assert_eq!(opened.inputs, audit.inputs);
}

fn check(cases: Vec<Case>, description: &str, committed: &str) {
    assert_eq!(
        serde_json::from_str::<Value>(committed).unwrap(),
        file_json(description, &cases)
    );
    for case in &cases {
        check_audit(&case.audit);
    }
}

