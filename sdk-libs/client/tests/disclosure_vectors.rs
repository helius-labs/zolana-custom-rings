struct Case {
    json: Value,
    audit: Audit,
}

struct Audit {
    transaction: ShieldedTransaction,
    frame: Vec<u8>,
    mode: RingMode,
    layout: DisclosureLayout,
    outputs: Vec<AuditedOutput>,
    input_trees: Vec<Option<u16>>,
    known: KnownUtxoIndex,
    escrowed: HashMap<[u8; 32], [u8; 32]>,
    inputs: Vec<AuditedInput>,
}

fn hex(bytes: impl AsRef<[u8]>) -> String {
    hex::encode(bytes)
}

fn hex_fields(fields: &[[u8; 32]]) -> Value {
    fields.iter().map(hex).collect()
}

fn assets() -> RingAssets {
    RingAssets::new([Mint::new(MINT, 7), Mint::new(OTHER_MINT, 8)]).unwrap()
}

fn transfer_json(transfer: &Transfer) -> Map<String, Value> {
    let mut map = Map::new();
    let tx_viewing_sk = transfer.tx_key.secret_bytes();
    map.insert("tx_viewing_sk".into(), hex(*tx_viewing_sk).into());
    map.insert(
        "tx_viewing_u".into(),
        hex(transfer.tx_key.pubkey().u()).into(),
    );
    map.insert("salt".into(), hex(transfer.salt).into());
    map.insert(
        "first_nullifier".into(),
        hex(transfer.first_nullifier).into(),
    );
    map.insert(
        "ring_program_id".into(),
        hex(transfer.ring.as_array()).into(),
    );
    map.insert("ring_id".into(), hex(transfer.ring_id()).into());
    map.insert("blinding_seed".into(), hex(transfer.blinding_seed()).into());
    map.insert("seed_out".into(), hex(transfer.seed_out()).into());
    map.insert("output_tree_id".into(), transfer.tree_id.into());
    map
}

fn utxo_json(utxo: &UtxoFields, map: &mut Map<String, Value>) {
    map.insert("owner_key".into(), hex(utxo.owner_key).into());
    map.insert("nullifier_pk".into(), hex(utxo.nullifier_pk).into());
    map.insert(
        "asset_address".into(),
        hex(utxo.asset_address.as_array()).into(),
    );
    map.insert("asset".into(), hex(utxo.asset()).into());
    map.insert("amount".into(), utxo.amount.into());
    map.insert("data_hash".into(), hex(utxo.data_hash).into());
    map.insert("ring_data_hash".into(), hex(utxo.ring_data_hash).into());
}

fn slot_json(output: &Output, slot: &Slot) -> Map<String, Value> {
    let mut map = Map::new();
    let kind = match output {
        Output::Ring {
            utxo,
            recipient_u,
            tag,
        } => {
            utxo_json(utxo, &mut map);
            match tag {
                Some(tag) => map.insert("tag".into(), hex(tag).into()),
                None => map.insert("recipient_u".into(), hex(recipient_u).into()),
            };
            "ring"
        }
        Output::Exit(utxo) => {
            utxo_json(utxo, &mut map);
            "exit"
        }
        Output::Dummy => "dummy",
    };
    map.insert("kind".into(), kind.into());
    map.insert("owner_tag".into(), hex(slot.output.view_tag).into());
    if let Some(secret) = slot.slot_secret {
        map.insert("slot_secret".into(), hex(secret).into());
    }
    if !matches!(output, Output::Dummy) {
        map.insert("ring_data_hash".into(), hex(slot.ring_data_hash).into());
    }
    map.insert("blinding".into(), hex(slot.blinding).into());
    if let Some(body) = slot.body {
        map.insert("body".into(), hex(body).into());
    }
    map.insert(
        "output_hash".into(),
        hex(slot.output.output_context.hash).into(),
    );
    map
}

fn disclosure_json(transfer: &Transfer, disclosure: &AuditDisclosure) -> Map<String, Value> {
    let plaintext = disclosure.fields().unwrap();
    let pad = DisclosurePad::new(&transfer.tx_key, &transfer.salt).unwrap();
    let published = pad.encrypt(&plaintext).unwrap();
    let zeros = vec![[0; 32]; plaintext.len()];
    let mut map = Map::new();
    map.insert("plaintext".into(), hex_fields(&plaintext));
    map.insert("pad".into(), hex_fields(&pad.encrypt(&zeros).unwrap()));
    map.insert("published".into(), hex_fields(&published));
    map.insert(
        "disclosure_chain".into(),
        hex(create_hash_chain_4_from_slice(&published).unwrap()).into(),
    );
    map
}

fn layout_value(frame: &[u8], rail: RingRail) -> u8 {
    RingTransactData::parse(&frame[1..], rail)
        .unwrap()
        .data()
        .audit_layout()
        .value()
}

fn escrowed_keys(outputs: &[Output]) -> HashMap<[u8; 32], [u8; 32]> {
    outputs
        .iter()
        .filter_map(|output| match output {
            Output::Ring { utxo, .. } | Output::Exit(utxo) => {
                Some((utxo.owner_key, utxo.nullifier_pk))
            }
            Output::Dummy => None,
        })
        .collect()
}

fn audited_outputs(outputs: &[Output], slots: &[Slot]) -> Vec<AuditedOutput> {
    (0u32..)
        .zip(outputs.iter().zip(slots))
        .map(|(slot_index, (output, slot))| AuditedOutput {
            slot_index,
            context: slot.output.output_context.clone(),
            opening: audited_opening(output, slot),
        })
        .collect()
}

fn ring_utxo(owner: u8, asset_address: Address, amount: u64) -> UtxoFields {
    UtxoFields {
        owner_key: [owner; 32],
        nullifier_pk: field(owner - 0x90),
        asset_address,
        amount,
        ..UtxoFields::default()
    }
}

fn ring_output(owner: u8, asset_address: Address, amount: u64) -> Output {
    Output::Ring {
        utxo: ring_utxo(owner, asset_address, amount),
        recipient_u: x25519_u(owner - 0x70),
        tag: None,
    }
}

/// A delivered transfer, its ring mode the one the escrow flag implies.
struct DeliveredCase<'a> {
    name: &'static str,
    outputs: &'a [Output],
    key_escrow: bool,
}

impl DeliveredCase<'_> {
    fn case(self) -> Case {
        let transfer = Transfer::fixture();
        let slots = transfer.slots(Rail::Delivered, self.outputs);
        let disclosure = transfer.disclosure(Rail::Delivered, self.outputs, self.key_escrow);
        let transaction = transfer.publish(Publish {
            slots: slots.iter().map(|slot| slot.output.clone()).collect(),
            disclosure: &disclosure,
            auditor: &auditor().pubkey(),
        });
        let layout = disclosure.layout();
        let frame = transfer.frame(Frame {
            tx: &transaction,
            layout,
        });
        let mut json = Map::new();
        json.insert("name".into(), self.name.into());
        json.insert(
            "layout".into(),
            layout_value(&frame, RingRail::Confidential).into(),
        );
        json.extend(transfer_json(&transfer));
        json.insert(
            "slots".into(),
            self.outputs
                .iter()
                .zip(&slots)
                .map(|(output, slot)| Value::Object(slot_json(output, slot)))
                .collect(),
        );
        json.extend(disclosure_json(&transfer, &disclosure));
        Case {
            json: Value::Object(json),
            audit: Audit {
                transaction,
                frame,
                mode: match self.key_escrow {
                    true => RingMode::ConfidentialEscrow,
                    false => RingMode::Confidential,
                },
                layout,
                outputs: audited_outputs(self.outputs, &slots),
                input_trees: vec![None],
                known: KnownUtxoIndex::default(),
                escrowed: escrowed_keys(self.outputs),
                inputs: Vec::new(),
            },
        }
    }
}

fn delivered_cases() -> Vec<Case> {
    let assets = [SOL, MINT, SOL, OTHER_MINT, SOL, MINT, SOL];
    let rings = |count: u8| {
        (0..count)
            .map(move |k| ring_output(0xb0 + k, assets[usize::from(k)], 100 * (u64::from(k) + 1)))
    };
    let dense: Vec<Output> = rings(7).chain([Output::Dummy]).collect();
    let exits: Vec<Output> = rings(6)
        .chain([Output::Exit(ring_utxo(0xe6, OTHER_MINT, 40)), Output::Dummy])
        .collect();
    let pair_exits: Vec<Output> = rings(1)
        .chain([Output::Exit(ring_utxo(0xe5, MINT, 40))])
        .collect();
    let quad_escrow: Vec<Output> = rings(3).chain([Output::Dummy]).collect();
    [
        ("dense", &dense, false),
        ("exits", &exits, false),
        ("escrow", &dense, true),
        ("exits_escrow", &exits, true),
        ("pair_exits", &pair_exits, false),
        ("quad_escrow", &quad_escrow, true),
    ]
    .into_iter()
    .map(|(name, outputs, key_escrow)| {
        DeliveredCase {
            name,
            outputs,
            key_escrow,
        }
        .case()
    })
    .collect()
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum AnonymousKey {
    /// Only ring notes, every input disclosed by its commitment.
    Commitment,
    /// A default-ring note among the spends, every input opens in full.
    Entry,
}

/// Spends of the sender paying two recipients, change under the sender tag, dummies past four outputs.
struct AnonymousCase {
    name: &'static str,
    key: AnonymousKey,
    exits: bool,
    inputs: usize,
    outputs: usize,
}

impl AnonymousCase {
    fn case(self) -> Case {
        let entry = self.key == AnonymousKey::Entry;
        let mut transfer = Transfer::fixture();
        transfer
            .nullifiers
            .extend((1..self.inputs).map(|index| field(0x1f - index as u8)));
        let sender_nullifier_pk = field(0x5a);
        let sender = |asset_address, amount| UtxoFields {
            owner_key: SENDER_KEY,
            nullifier_pk: sender_nullifier_pk,
            asset_address,
            amount,
            ..UtxoFields::default()
        };
        let change_tag = field(0x5c);
        let change = Output::Ring {
            utxo: sender(MINT, 500),
            recipient_u: [0; 32],
            tag: Some(change_tag),
        };
        let change_stream = json!({"stream": "change"});
        let payment = |owner, asset_address, amount, tag| {
            (
                Output::Ring {
                    utxo: ring_utxo(owner, asset_address, amount),
                    recipient_u: [0; 32],
                    tag: Some(field(tag)),
                },
                json!({"stream": "payment"}),
            )
        };
        let mut paid = vec![
            payment(0xb5, SOL, 4000, 0x31),
            payment(0xb6, MINT, 2500, 0x32),
        ];
        paid.extend(match self.exits {
            true => [
                (Output::Exit(ring_utxo(0xe7, SOL, 1000)), Value::Null),
                (change, change_stream),
            ],
            false => [(change, change_stream), (Output::Dummy, Value::Null)],
        });
        paid.resize_with(self.outputs, || (Output::Dummy, Value::Null));
        let (outputs, streams): (Vec<Output>, Vec<Value>) = paid.into_iter().unzip();
        let slots = transfer.slots(Rail::Anonymous, &outputs);
        let spent: Vec<_> = [(SOL, 5000), (MINT, 3000), (SOL, 1500)][..self.inputs]
            .iter()
            .enumerate()
            .map(|(index, (asset_address, amount))| {
                (
                    sender(*asset_address, *amount),
                    field(0x60 + index as u8),
                    (index == 0 || !entry).then_some(transfer.ring),
                )
            })
            .collect();
        let commitments: Vec<[u8; 32]> = spent
            .iter()
            .map(|(utxo, blinding, ring)| {
                utxo.commitment(Placement {
                    blinding: *blinding,
                    ring: *ring,
                    tree_id: transfer.tree_id,
                })
            })
            .collect();
        let inputs = match self.key {
            AnonymousKey::Entry => AnonymousInputs::Openings {
                sender_key: SENDER_KEY,
                sender_nullifier_pk,
                inputs: spent
                    .iter()
                    .map(|(utxo, blinding, _)| Some(input_opening(utxo, *blinding)))
                    .collect(),
            },
            AnonymousKey::Commitment => AnonymousInputs::commitments(
                &commitments.iter().copied().map(Some).collect::<Vec<_>>(),
            )
            .unwrap(),
        };
        let disclosure = transfer.anonymous_disclosure(&outputs, inputs);
        let AuditDisclosure::Anonymous(anonymous) = &disclosure else {
            unreachable!("an anonymous transfer takes the anonymous layout");
        };
        let class = anonymous.layout.key.class();
        let transaction = transfer.publish(Publish {
            slots: slots.iter().map(|slot| slot.output.clone()).collect(),
            disclosure: &disclosure,
            auditor: &auditor().pubkey(),
        });
        let layout = disclosure.layout();
        let frame = transfer.frame(Frame {
            tx: &transaction,
            layout,
        });
        let mut json = Map::new();
        json.insert("name".into(), self.name.into());
        json.insert(
            "layout".into(),
            layout_value(&frame, RingRail::Anonymous).into(),
        );
        json.extend(transfer_json(&transfer));
        json.insert("sender_key".into(), hex(SENDER_KEY).into());
        json.insert(
            "sender_nullifier_pk".into(),
            hex(sender_nullifier_pk).into(),
        );
        json.insert(
            "key".into(),
            match self.key {
                AnonymousKey::Entry => "entry",
                AnonymousKey::Commitment => "commitment",
            }
            .into(),
        );
        json.insert("class".into(), class.into());
        json.insert(
            "inputs".into(),
            spent
                .iter()
                .zip(&transfer.nullifiers)
                .zip(&commitments)
                .map(|(((utxo, blinding, ring), nullifier), commitment)| {
                    json!({
                        "nullifier": hex(nullifier),
                        "asset_address": hex(utxo.asset_address.as_array()),
                        "asset": hex(utxo.asset()),
                        "amount": utxo.amount,
                        "blinding": hex(blinding),
                        "input_tree_id": transfer.tree_id,
                        "ring": if ring.is_some() { "ring" } else { "default" },
                        "owner_hash": hex(utxo.owner_hash()),
                        "commitment": hex(commitment),
                    })
                })
                .collect(),
        );
        json.insert(
            "slots".into(),
            outputs
                .iter()
                .zip(&slots)
                .zip(streams)
                .map(|((output, slot), stream)| {
                    let mut map = slot_json(output, slot);
                    if let Value::Object(stream) = stream {
                        map.extend(stream);
                    }
                    Value::Object(map)
                })
                .collect(),
        );
        json.extend(disclosure_json(&transfer, &disclosure));
        let known = spent
            .iter()
            .zip(&commitments)
            .map(|((utxo, blinding, ring), commitment)| {
                let placement = Placement {
                    blinding: *blinding,
                    ring: *ring,
                    tree_id: transfer.tree_id,
                };
                (*commitment, known_utxo(utxo, placement))
            })
            .collect();
        let inputs = spent
            .iter()
            .zip(&transfer.nullifiers)
            .zip(&commitments)
            .map(|(((utxo, blinding, ring), nullifier), commitment)| {
                let commitment = *commitment;
                AuditedInput {
                    nullifier: *nullifier,
                    opening: InputOpening::Opened(AuditedInputOpening {
                        asset: utxo.asset(),
                        mint: Some(utxo.asset_address),
                        amount: utxo.amount,
                        blinding: *blinding,
                        ring: Some(match ring {
                            Some(_) => InputRing::Ring { commitment },
                            None => InputRing::Default { commitment },
                        }),
                    }),
                }
            })
            .collect();
        Case {
            json: Value::Object(json),
            audit: Audit {
                transaction,
                frame,
                mode: RingMode::Anonymous,
                layout,
                outputs: audited_outputs(&outputs, &slots),
                input_trees: vec![Some(transfer.tree_id); self.inputs],
                known,
                escrowed: HashMap::new(),
                inputs,
            },
        }
    }
}

