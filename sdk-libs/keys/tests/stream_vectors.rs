//! One worked ring stream per label and per record kind, the ignored `write_stream_vectors`
//! regenerates the file Go and TypeScript read.

use aes::{
    cipher::{KeyIvInit, StreamCipher},
    Aes256,
};
use ctr::Ctr32BE;
use custom_ring_interface::{
    domain::{AUDIT_STREAM_LABEL, REGISTER_KEY_LABEL},
    STREAM_FIRST_COUNTER,
};
use serde_json::{json, Value};
use spr_hasher::{
    primitives::{pack_be, right_align},
    Hasher, Poseidon,
};
use spr_keypair::{ViewingKey, X25519Keypair, X25519Pubkey};
use zolana_ring_keys::RingStream;

const VECTOR: &str = include_str!("../../../test-vectors/audit/auditor-stream.json");

const DESCRIPTION: &str = "Worked ring streams, one per label and per record kind. head = Poseidon(right_align(label || 0x00), secret), tail = Poseidon(right_align(label || 0x01), secret), key = low31_be(head) || low13_be(tail)[0], nonce = low13_be(tail)[1..13], ct = AES-256-CTR(key, nonce || u32be(counter), plaintext). secret = Poseidon(CR_S, pack_be(X25519(eph_sk, auditor_u)), pack_be(0x04 || eph_u), pack_be(0x04 || auditor_u)) for the auditor stream and the register key. Envelope at counter 2, record of slot i at counter R0 + i * R with R0 = 4 + E_max(key). Generated by sdk-libs/keys/tests/stream_vectors.rs.";

fn scalar(seed: u8) -> [u8; 32] {
    let mut out = core::array::from_fn(|i| seed ^ i as u8);
    out[0] = 0x01;
    out
}

fn field(byte: u8) -> [u8; 32] {
    let mut out = [byte; 32];
    out[0] = 0;
    out
}

struct Parties {
    eph: X25519Keypair,
    auditor: X25519Pubkey,
    secret: [u8; 32],
}

fn parties() -> Parties {
    let eph = X25519Keypair::from_bytes(&scalar(0x22));
    let auditor = X25519Keypair::from_bytes(&scalar(0x33)).pubkey();
    let [dh0, dh1] = pack_be(&eph.ecdh(&auditor).unwrap());
    let [eph0, eph1] = pack_be(eph.pubkey().as_bytes());
    let [aud0, aud1] = pack_be(auditor.as_bytes());
    let secret = Poseidon::hashv(&[
        &right_align(b"CR_S"),
        &dh0,
        &dh1,
        &eph0,
        &eph1,
        &aud0,
        &aud1,
    ])
    .unwrap();
    Parties {
        eph,
        auditor,
        secret,
    }
}

struct Worked<'a> {
    name: &'a str,
    label: &'a [u8; 9],
    secret: [u8; 32],
    counter: u32,
    plaintext: Vec<u8>,
}

impl Worked<'_> {
    /// The key and nonce come from the schedule's text, the ciphertext from the SDK stream.
    fn json(self) -> Value {
        let mut tag = [0u8; 10];
        tag[..9].copy_from_slice(self.label);
        let head = Poseidon::hashv(&[&right_align(&tag), &self.secret]).unwrap();
        tag[9] = 1;
        let tail = Poseidon::hashv(&[&right_align(&tag), &self.secret]).unwrap();
        let key = [&head[1..], &tail[19..20]].concat();
        let nonce = &tail[20..];
        let mut ciphertext = self.plaintext.clone();
        RingStream::new(&self.secret, self.label)
            .unwrap()
            .apply_at(self.counter, &mut ciphertext);
        let mut iv = [0u8; 16];
        iv[..12].copy_from_slice(nonce);
        iv[12..].copy_from_slice(&self.counter.to_be_bytes());
        let mut expected = self.plaintext.clone();
        let key_bytes: [u8; 32] = key.clone().try_into().unwrap();
        Ctr32BE::<Aes256>::new((&key_bytes).into(), (&iv).into()).apply_keystream(&mut expected);
        assert_eq!(ciphertext, expected, "{}", self.name);
        json!({
            "name": self.name,
            "label": String::from_utf8_lossy(self.label),
            "secret": hex::encode(self.secret),
            "head": hex::encode(head),
            "tail": hex::encode(tail),
            "key": hex::encode(key),
            "nonce": hex::encode(nonce),
            "counter": self.counter,
            "plaintext": hex::encode(&self.plaintext),
            "ciphertext": hex::encode(ciphertext),
        })
    }
}

fn be64(amount: u64) -> [u8; 8] {
    amount.to_be_bytes()
}

fn concat(parts: &[&[u8]]) -> Vec<u8> {
    parts.concat()
}

fn labels() -> Vec<Value> {
    let secret = parties().secret;
    let tx = ViewingKey::from_bytes(&scalar(0x11));
    let tx_viewing_sk = *tx.secret_bytes();
    let (input_0, input_1) = (field(0x60), field(0x61));
    let (sender_key, sender_nullifier_pk) = ([0xa1; 32], field(0x5a));
    let (asset, blinding) = (field(0x0a), field(0x40));
    let hashes = concat(&[&input_0, &input_1]);
    let envelope = |evidence: &[u8]| concat(&[&tx_viewing_sk, evidence]);
    let auditor_stream = |name, plaintext| Worked {
        name,
        label: AUDIT_STREAM_LABEL,
        secret,
        counter: STREAM_FIRST_COUNTER,
        plaintext,
    };
    [
        auditor_stream("envelope_signer", envelope(&hashes)),
        auditor_stream("envelope_in_proof_n2", envelope(&hashes)),
        auditor_stream("envelope_commitment_n2", envelope(&hashes)),
        auditor_stream(
            "envelope_entry_n1",
            envelope(&concat(&[
                &sender_key,
                &sender_nullifier_pk,
                &input_0,
                &be64(500),
                &asset,
                &blinding,
            ])),
        ),
        Worked {
            name: "register_key",
            label: REGISTER_KEY_LABEL,
            secret,
            counter: STREAM_FIRST_COUNTER,
            plaintext: right_align(&[0x07; 31]).to_vec(),
        },
    ]
    .into_iter()
    .map(Worked::json)
    .collect()
}

fn record_counter(key: RecordKey, slot: u32) -> u32 {
    let (first, blocks) = match key {
        RecordKey::Commitment => (4 + 8, 7),
        RecordKey::Confidential => (4 + 4, 5),
    };
    first + slot * blocks
}

#[derive(Clone, Copy)]
enum RecordKey {
    Commitment,
    Confidential,
}

fn records() -> Vec<Value> {
    let secret = parties().secret;
    let owner_key = [0xb0; 32];
    let (asset, nullifier_pk) = (field(0x0a), field(0x20));
    let anonymous = RecordKey::Commitment;
    let confidential = RecordKey::Confidential;
    let record = |name, key, slot, plaintext| Worked {
        name,
        label: AUDIT_STREAM_LABEL,
        secret,
        counter: record_counter(key, slot),
        plaintext,
    };
    [
        record(
            "anonymous_ring_output_slot_1",
            anonymous,
            1,
            concat(&[&owner_key, &asset, &be64(4000), &nullifier_pk]),
        ),
        record("anonymous_dummy_slot_3", anonymous, 3, vec![0; 104]),
        record(
            "anonymous_exit_slot_2",
            anonymous,
            2,
            concat(&[&asset, &be64(1000), &nullifier_pk]),
        ),
        record(
            "confidential_exit_slot_1",
            confidential,
            1,
            concat(&[&asset, &be64(1000), &nullifier_pk]),
        ),
        record(
            "confidential_exit_key_escrow_slot_1",
            confidential,
            1,
            concat(&[&asset, &be64(1000)]),
        ),
    ]
    .into_iter()
    .map(Worked::json)
    .collect()
}

fn vector() -> Value {
    let Parties { eph, auditor, .. } = parties();
    json!({
        "description": DESCRIPTION,
        "eph_sk": hex::encode(*eph.secret_bytes()),
        "eph_u": hex::encode(eph.pubkey().u()),
        "auditor_u": hex::encode(auditor.u()),
        "labels": labels(),
        "records": records(),
    })
}

#[test]
fn stream_vectors_match() {
    assert_eq!(serde_json::from_str::<Value>(VECTOR).unwrap(), vector());
}

